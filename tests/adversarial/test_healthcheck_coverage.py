def _hostile_report():
    e = _entry("ipahealthcheck.zz.brand_new", "Evil\x1b[31mCheck", "WARNING",
               msg="$(rm -rf /) `id` \x1b]0;pwn\x07 password=hunter2 " + "A" * 5000)
    return run_diagnosis(_bundle([e]))


def test_json_preserves_undiagnosed_findings_structurally_and_sanitised():
    data = report_to_dict(_hostile_report())
    u = data["undiagnosed_findings"]
    assert u and {"source", "check", "severity", "message", "reason", "check_crashed"} <= set(u[0])
    blob = json.dumps(u)
    assert "\x1b" not in blob and len(u[0]["message"]) <= 300
    assert data["unclaimed_warnings"] == 1  # legacy count key kept for compatibility


def test_console_lists_undiagnosed_findings_by_name_default_and_details():
    report = run_diagnosis(_bundle([
        _entry("ipahealthcheck.zz.brand_new", "OddCheck", "WARNING", msg="odd but not fatal"),
    ]))
    for details in (False, True):
        buf = io.StringIO()
        render_report(report, Console(file=buf, width=140, force_terminal=False), details=details)
        out = buf.getvalue()
        assert "UNDIAGNOSED" in out and "OddCheck" in out and "odd but not fatal" in out
    assert "check available since" in out or "not in this build" in out  # --details adds version context


