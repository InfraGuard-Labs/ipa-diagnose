"""Zero-silent-failure guarantee for ipa-healthcheck findings.

Every failing result of every upstream check (inventory snapshot of ipa-healthcheck 0.12, 0.16,
0.19 and master, generated by scripts/inventory_healthcheck.py) must end up either cited by a
diagnosis or listed by name in ``undiagnosed_findings`` - never silently dropped. A check that
does not exist yet (or a hostile/malformed one) must never be claimed by an existing rule."""

from __future__ import annotations

import io
import json
import pathlib

import pytest
from rich.console import Console

from ipa_diagnose.engine.model import DiagnosisStatus
from ipa_diagnose.engine.run import run_diagnosis
