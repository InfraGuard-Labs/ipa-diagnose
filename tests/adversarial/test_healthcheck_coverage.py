def test_expired_directory_server_certificate_is_a_certificate_diagnosis_not_an_nss_format_one():
    e = _entry("ipahealthcheck.ds.nss_ssl", "NssCheck", "CRITICAL", key="DSCERTLE0002",
               msg="The certificate (Server-Cert) has expired", items=["Expiration"])
    report = run_diagnosis(_bundle([e]))
    d = _rule(report, "ds-certificate-expiry")
    assert d is not None and d.status == DiagnosisStatus.DIAGNOSED
    assert "expired" in d.title.lower()
    assert _rule(report, "nss-tls-db-format") is None


def test_unknown_nss_check_result_is_not_a_db_format_or_expiry_diagnosis():
    e = _entry("ipahealthcheck.ds.nss_ssl", "NssCheck", "ERROR", key="DSCERTLE9999", msg="something new")
    report = run_diagnosis(_bundle([e]))
    assert _rule(report, "nss-tls-db-format") is None and _rule(report, "ds-certificate-expiry") is None
    assert any(u.check == "NssCheck" for u in report.undiagnosed_findings) or _rule(report, "unexplained-findings")


