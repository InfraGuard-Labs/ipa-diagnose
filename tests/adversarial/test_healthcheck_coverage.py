from ipa_diagnose.evidence.model import EvidenceBundle, EvidenceItem
from ipa_diagnose.render.console import render_report
from ipa_diagnose.render.json_output import report_to_dict

SNAPSHOT = json.loads((pathlib.Path(__file__).parents[1] / "data" / "healthcheck_inventory.json").read_text(encoding="utf-8"))
FAIL_LEVELS = ("WARNING", "ERROR", "CRITICAL")
GOOD = {
    "source": "ipahealthcheck.meta.services", "check": "dirsrv", "result": "SUCCESS", "uuid": "good",
    "when": "20260101000000Z", "duration": "0.01", "kw": {"status": True},
}


def _entry(source, check, level, key=None, msg=None, uid="x", **kw):
    body = {"key": key or check}
    if msg is not None:
        body["msg"] = msg
    body.update(kw)
    return {"source": source, "check": check, "result": level, "uuid": f"{source}.{check}.{level}.{key}.{uid}",
            "when": "20260101000000Z", "duration": "0.01", "kw": body}


def _bundle(entries, items=()):
    findings = parse_healthcheck_results([GOOD] + list(entries), command="t", live=False)
    return EvidenceBundle(hostname="h", collected_at=EvidenceBundle.now(), findings=findings, items=list(items))


def _rule(report, rule_id):
    return next((d for d in report.diagnoses if d.rule_id == rule_id), None)


def _accounted_for(report, entry):
    cited = {r.evidence_id for d in report.diagnoses for r in list(d.evidence_for) + list(d.evidence_against)}
    listed = {(u.source, u.check) for u in report.undiagnosed_findings}
    return entry["uuid"] in cited or (entry["source"], entry["check"]) in listed


def _rows(tag):
    for cid, info in sorted(SNAPSHOT[tag].items()):
        module = info["module"]
        check = cid[len(module) + 1:]
        levels = [lv for lv in info["levels"] if lv in FAIL_LEVELS] or list(FAIL_LEVELS)
        if info["levels"] == ["SUCCESS"]:
            continue
        for level in levels:
            for key in [None] + list(info["keys"]):
                yield module, check, level, key


@pytest.mark.parametrize("tag", sorted(SNAPSHOT))
def test_every_failing_upstream_check_is_accounted_for(tag):
    silent = []
    total = 0
    for module, check, level, key in _rows(tag):
        for shape in ("msg", "crash"):
            if shape == "msg":
                e = _entry(module, check, level, key, msg=f"synthetic {level} from {check}")
            else:
                e = _entry(module, check, level, key, exception="boom", traceback="Traceback ...")
                e["kw"].pop("key")
            total += 1
            if not _accounted_for(run_diagnosis(_bundle([e])), e):
                silent.append(f"{module}.{check}/{level}/{key}/{shape}")
    assert total > 100
    assert not silent, f"silently unhandled in ipa-healthcheck {tag}: {silent[:10]}"


FUTURE_SOURCES = sorted({v["module"] for v in SNAPSHOT["master"].values()}) + ["ipahealthcheck.zz.brand_new"]


@pytest.mark.parametrize("source", FUTURE_SOURCES)
def test_unknown_future_check_is_surfaced_and_never_claimed_by_a_rule(source):
    for level in FAIL_LEVELS + ("FATAL",):
        for shape in ("msg", "nomsg", "exception", "nokw"):
            e = _entry(source, "ZzFutureCheck", level, msg="a brand new failure" if shape == "msg" else None)
            if shape == "exception":
                e["kw"] = {"exception": "x", "traceback": "y"}
            if shape == "nokw":
                e.pop("kw")
            report = run_diagnosis(_bundle([e]))
            claimed = [d.rule_id for d in report.diagnoses if e["uuid"] in {r.evidence_id for r in d.evidence_for}
                       and d.status == DiagnosisStatus.DIAGNOSED]
            assert not claimed, f"{source}/{level}/{shape} wrongly diagnosed by {claimed}"
            assert _accounted_for(report, e), f"{source}/{level}/{shape} silently dropped"


def test_more_than_the_grouped_limit_of_findings_are_all_named():
    entries = [_entry("ipahealthcheck.zz.brand_new", f"Chk{i}", "ERROR", msg=f"problem {i}") for i in range(15)]
    report = run_diagnosis(_bundle(entries))
    names = {u.check for u in report.undiagnosed_findings}
    cited = {r.evidence_id for d in report.diagnoses for r in d.evidence_for}
    for e in entries:
        assert e["check"] in names or e["uuid"] in cited


